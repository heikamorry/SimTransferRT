"""Versioned, evidence-qualified protocol acceptance tables; no wire changes.

Sender rows are generated by the C++ exporter, so GUI/CLI and combined reports
share the same measurement definitions. Legacy reports remain readable, but
missing measurements are never invented or interpreted as successful zeros.
"""
