def row(identifier, requirement, measurement, threshold, actual=None,
        status='not_measured', reason='', evidence=()):
    assert status in LABELS
    return dict(id=identifier, requirement=requirement, measurement=measurement,
                threshold=threshold, actual='未检测' if actual is None else str(actual),
                status=status, status_label=LABELS[status], reason=reason,
                evidence=list(evidence))


def table(rows, scope):
    statuses = [item['status'] for item in rows]
    overall = ('fail' if 'fail' in statuses else
               'not_measured' if not rows or 'not_measured' in statuses else 'pass')
    return dict(schema_version=1, scope=scope, overall_status=overall,
                overall_status_label=LABELS[overall],
                status_counts={key: statuses.count(key) for key in LABELS},
                note='各行仅覆盖所列测量口径；缺少硬件、物理链路或渲染证据时不宣称完整协议达标。',
                rows=rows)


def _count(value):
    return type(value) is int and value >= 0


def _number(value):
    try:
        return type(value) in (int, float) and math.isfinite(value) and value >= 0
    except (OverflowError, TypeError):
        return False


def _hist(report, name):
    timing = report.get('receiver_timing', {})
    if not isinstance(timing, dict) or timing.get('version') not in (1, 2):
        return None
    if name in ('frame_first_seen_to_validation_complete', 'last_ingest_to_validation_complete') and timing['version'] < 2:
        return None
    histograms = timing.get('histograms', {})
    h = histograms.get(name) if isinstance(histograms, dict) else None
    if not isinstance(h, dict) or not _count(h.get('count')) or h['count'] == 0:
        return None
    if not all(_number(h.get(key)) for key in ('min_us', 'max_us')) or h['min_us'] > h['max_us']:
        return None
    return h


def _display_hist(hist):
    if hist is None:
        return '无有效观测'
    return ('n={count}, min={min_us}us, max={max_us}us, '
            'P99={p99_us}us, P99.9={p999_us}us').format_map(
                {'p99_us': '未检测', 'p999_us': '未检测', **hist})


def sender_rows(sender):
    source = sender.get('acceptance_table', {})
    if not isinstance(source, dict): source = {}
    source_rows = source.get('rows', []) if isinstance(source, dict) else []
    required = ('id', 'requirement', 'measurement', 'threshold', 'actual', 'reason')
    if source.get('schema_version') == 1 and isinstance(source_rows, list) and len(source_rows) <= 128:
        good = [item for item in source_rows if isinstance(item, dict) and
                all(isinstance(item.get(key), str) and len(item[key]) <= 8192 for key in required) and
                item.get('status') in LABELS and isinstance(item.get('evidence'), list) and
                len(item['evidence']) <= 32 and all(isinstance(path, str) and len(path) <= 4096 for path in item['evidence'])]
        if len(good) == len(source_rows) and len({r['id'] for r in good}) == len(good):
            rows = copy.deepcopy(good)
            for item in rows: item['status_label'] = LABELS[item['status']]
            known = {r['id'] for r in rows}
            rows += [row(key, title, '发送端本地测量', '见协议要求',
                         reason='报告未包含此项验收数据。')
                     for key, title in SENDER_REQUIREMENTS.items() if key not in known]
            return rows
    return [row(key, title, '发送端本地测量', '见协议要求',
                reason='旧版、缺失或无效的发送端验收表；不能从缺失字段推断通过。')
            for key, title in SENDER_REQUIREMENTS.items()]


def receiver_rows(report):
    t = report.get('receiver_timing', {})
    e = t.get('evidence', {}) if isinstance(t, dict) and t.get('version') in (1, 2) else {}
    if not isinstance(e, dict): e = {}
    rows = []
    def add_metric(identifier, requirement, name, threshold, *, violations=None, expected=None,
                   reason='', evaluate=True, minimum_us=None):
        h = _hist(report, name)
        valid = h is not None and (expected is None or
                                  (_count(e.get(expected)) and h['count'] == e[expected]))
        counter = e.get(violations) if violations else None
        if violations and (not _count(counter) or h is None or counter > h['count']): valid = False
        state = 'not_measured'
        if valid and evaluate:
            state = 'fail' if counter or (minimum_us is not None and h['min_us'] < minimum_us) else 'pass'
        rows.append(row(identifier, requirement,
                        '接收端用户态单调时钟；' + name, threshold,
                        _display_hist(h) + (f'，违规={counter}' if counter is not None else ''),
                        state, reason if valid else '无有效样本或观察分母/计数不完整；' + reason,
                        ['receiver-report.json:receiver_timing.histograms.' + name] +
                        (['receiver-report.json:receiver_timing.evidence.' + violations] if violations else [])))

    add_metric('nack_first_request', '缺片发现后的首个可用轮询立即请求',
               'discovery_to_first_request', '同一可用poll轮；实际耗时另列',
               violations='first_request_same_poll_violations', expected='first_requests',
               reason='逻辑轮次通过不代表OS零延迟；外部暂停体现在实测耗时。')
    add_metric('nack_retry_interval', '同片后续请求满10ms再请求',
               'request_interval', '间隔≥10000us；浮点比较容差沿用模型EPSILON',
               violations='early_retry_intervals', expected='retry_intervals',
               minimum_us=10000,
               reason='仅检验不提前；迟到分布另列，不据此宣称准时。')
    add_metric('nack_scheduler_lateness', '请求调度迟到观测',
               'request_scheduler_lateness', '原文未规定调度迟到容差', evaluate=False,
               reason='有实测数据，但无独立验收容差；不擅自设定通过阈值。')
    requested, maximum = report.get('requested_fragments'), report.get('max_requests_for_fragment')
    valid_budget = (_count(requested) and requested > 0 and _count(maximum) and 1 <= maximum <= requested and
                    _count(e.get('request_budget_exceeded')) and e['request_budget_exceeded'] <= requested)
    rows.append(row('nack_request_budget', '同一缺片最多请求三次',
                    '每片逻辑请求预算；多区间拆包和故障注入重复发送另计', '≤3次',
                    f'请求片次={requested}，同片最大={maximum}',
                    ('fail' if maximum > 3 or e['request_budget_exceeded'] else 'pass') if valid_budget else 'not_measured',
                    '本地sendto失败仍消耗一次预算；没有请求样本不视为通过。',
                    ['receiver-report.json:max_requests_for_fragment', 'receiver-report.json:receiver_timing.evidence.request_budget_exceeded']))
    add_metric('nack_silence_tail', '2ms静默尾部缺片检测', 'silence_tail_lateness',
               '计划时刻=最后唯一片+2000us；调度容差未约定', evaluate=False,
               reason='显示超过计划时刻的迟到；更新帧触发另列，不能混作2ms静默。')
    add_metric('nack_newer_frame_tail', '更新帧触发旧帧尾部缺片登记', 'newer_frame_to_tail_discovery',
               '观察更新帧的同一ingest轮；非网卡到达时间', evaluate=False,
               reason='用于区分尾部发现来源；尚不把同一用户态时间读数当作零硬件延迟。')
    expiry = _hist(report, 'third_request_to_expiry')
    expired_frames, early_frames, due_fragments = (e.get('expired_frames'), e.get('early_expiries'), e.get('third_expiry_fragments'))
    frame_evidence = (_count(expired_frames) and expired_frames > 0 and _count(early_frames) and
                      early_frames <= expired_frames and report.get('expired') == expired_frames)
    fragment_evidence = (expiry is not None and _count(due_fragments) and expiry['count'] == due_fragments and
                         due_fragments >= expired_frames) if frame_evidence else False
    expiry_state = ('fail' if frame_evidence and early_frames > 0 else
                    ('fail' if expiry['min_us'] < 10000 else 'pass') if fragment_evidence else 'not_measured')
    rows.append(row('nack_expiry_wait', '第三次请求后再等10ms才作废',
                    '接收用户态：提前作废按帧计数；第三次请求等待按实际到期缺片计数',
                    '等待≥10000us；提前作废帧=0',
                    _display_hist(expiry) + f'；作废帧={expired_frames}；提前作废帧={early_frames}',
                    expiry_state,
                    '同帧较晚缺片不进入到期片分母；没有到期片样本也不能掩盖已记录的提前作废。',
                    ['receiver-report.json:receiver_timing.histograms.third_request_to_expiry',
                     'receiver-report.json:receiver_timing.evidence.expired_frames',
                     'receiver-report.json:receiver_timing.evidence.early_expiries']))
    add_metric('nack_total_wait', '发现缺片至整帧作废约30ms', 'missing_discovery_to_frame_expiry',
               '名义约30000us；“约”的容差尚未定义', evaluate=False,
               reason='报告实际跨度，保留未检测判定，避免替协议擅自定义允许超时。')
    add_metric('nack_recovery', '请求缺片补回耗时', 'first_request_to_recovery',
               '协议未给固定RTT上限；不依赖重传flags', evaluate=False,
               reason='首请求到补回；最后请求到补回另见原始直方图。')
    add_metric('receiver_ingest_span', '首片至末片进入处理跨度（旧指标）', 'frame_first_seen_to_complete',
               '首片至末片进入ingest；无独立固定上限', evaluate=False,
               expected='completed_frames', reason='保留旧数值口径；不含末片CRC、拼接和模块校验的处理尾耗时。')
    add_metric('receiver_reassembly_timing', '首片处理入口至重组校验完成', 'frame_first_seen_to_validation_complete',
               '末片CRC、完整帧拼接及模块校验后重新读时钟；无独立固定上限', evaluate=False,
               expected='validation_completed_frames', reason='需要v2完成时钟观测；不含回调/渲染，不是发送采样到屏幕的端到端延迟。')
    add_metric('receiver_validation_tail', '末片处理入口至重组校验完成', 'last_ingest_to_validation_complete',
               '末片ingest入口至校验后时钟；无独立固定上限', evaluate=False,
               expected='validation_completed_frames', reason='包含末片解码、CRC、拼接和模块校验；墙钟跨度不等于纯CPU耗时。')
    rows.append(row('receiver_delivery', '收发联合完整性',
                    '成功构建帧ID与接收终态清单逐一核对', '按本次场景的预期接收结局',
                    f'本地完整={report.get("completed", "未检测")}，作废={report.get("expired", "未检测")}',
                    reason='接收端单独报告不知道从未到达的帧；需配对发送端报告。',
                    evidence=['receiver-report.json:frame_manifest']))
    rows.append(row('render_synchronization', '全部模块同步渲染',
                    '生产接收端同帧全部模块绘制', '按TS同步消费、整体渲染',
                    '接收器为诊断测试桩，未实现渲染', reason='receiver_rendering_implemented=false；不能用completed代替已显示。',
                    evidence=['receiver-report.json:receiver_rendering_implemented']))
    return rows


def receiver_acceptance(report):
    return table(receiver_rows(report), 'receiver-local')


def combined_acceptance(sender, receiver, summary):
    rows = {r['id']: r for r in sender_rows(sender)}
    for item in receiver_rows(receiver): rows[item['id']] = item
    run_id = summary.get('run_id')
    identity = bool(isinstance(run_id, str) and run_id and
                    sender.get('run_id') == run_id == receiver.get('run_id'))
    process_ok = (type(summary.get('sender_exit')) is int and summary['sender_exit'] == 0 and
                  type(summary.get('receiver_exit')) is int and summary['receiver_exit'] == 0 and
                  summary.get('failure') is None)
    full = (summary.get('case') in ('A64', 'A1', 'B64', 'B1', 'C', 'CRC') and
            not str(receiver.get('mode', '')).startswith('drain'))
    # Recompute from original reports instead of trusting a summary's claim.
    # Late import avoids the orchestrator/report-renderer import cycle.
    from run_diagnostics import reconcile
    try:
        rec = reconcile(sender, receiver)
    except (ValueError, TypeError, KeyError, AttributeError, OverflowError):
        rec = {}
    stated = summary.get('reception', {})
    compare_keys = ('sender_built_denominator', 'completed', 'retired', 'wholly_missing', 'still_in_flight')
    consistent_summary = (isinstance(stated, dict) and stated.get('exact_classification_available') is True and
                          stated.get('manifest_consistent') is True and
                          all(stated.get(k) == rec.get(k) and k in rec for k in compare_keys))
    evidence_ok = (identity and process_ok and full and consistent_summary and isinstance(rec, dict) and
                   isinstance(sender.get('built_manifest'), dict) and
                   rec.get('exact_classification_available') is True and
                   rec.get('manifest_consistent') is True and
                   _count(rec.get('sender_built_denominator')) and rec['sender_built_denominator'] > 0 and
                   type(summary.get('functional_target_pass')) is bool and
                   all(_count(rec.get(key)) for key in ('completed', 'retired', 'wholly_missing', 'still_in_flight')))
    if evidence_ok:
        expected_outcomes = (rec['completed'] == 0 and rec['retired_by_reason'].get('expired') == rec['sender_built_denominator']
                             if summary.get('case') == 'C' else
                             rec['completed'] == rec['sender_built_denominator'] and rec['retired'] == 0)
        raw_ok = (expected_outcomes and all(rec.get(k) == 0 for k in
                  ('wholly_missing', 'still_in_flight', 'unexpected_receiver', 'unclassified_seen')) and
                  all(_count(receiver.get(k)) and receiver[k] == 0 for k in ('metadata_failures', 'module_failures', 'active_evictions')) and
                  _count(receiver.get('max_requests_for_fragment')) and receiver['max_requests_for_fragment'] <= 3)
        state = 'pass' if summary['functional_target_pass'] and raw_ok else 'fail'
        actual = ('构建={sender_built_denominator}，完整={completed}，作废={retired}，'
                  '完全未见={wholly_missing}，在途={still_in_flight}').format_map(rec)
        reason = ('按当前故障场景核对；故意持续丢片的预期结局是作废，不代表完整交付。'
                  if summary.get('case') == 'C' else '以发送端构建清单为分母；socket发送成功不等于对端收到。')
        if state == 'fail': reason += ' ' + '; '.join(map(str, summary.get('functional_failures', [])))
    else:
        state, actual = 'not_measured', '缺少可信收发联合证据'
        reason = '需相同非空run_id、双方正常退出、完整清单和非排水接收模式；旧版/错配/截断报告不得冒充通过。'
    rows['receiver_delivery'] = row('receiver_delivery', '收发联合完整性',
        '发送端built_manifest与接收frame_manifest核对', '本次场景预期结局；不将故障恢复测试当成无丢包证明',
        actual, state, reason, ['sender-report.json:built_manifest', 'receiver-report.json:frame_manifest', 'summary.json:reception'])
    pairing = ('pass' if identity and process_ok and full else
               'fail' if sender and receiver and full and (not identity or not process_ok) else 'not_measured')
    rows['report_pairing'] = row('report_pairing', '收发报告身份与运行完整性',
        'run_id、退出码及运行错误', '相同run_id、双方exit 0、非排水模式',
        f'run_id={run_id}，sender_exit={summary.get("sender_exit")}，receiver_exit={summary.get("receiver_exit")}',
        pairing, '不拼接不同运行的数据；单端和排水测试不做联合验收。',
        ['summary.json:run_id', 'summary.json:sender_exit', 'summary.json:receiver_exit'])
    return table(list(rows.values()), 'sender-receiver-combined')


def markdown(acceptance, title='UDP协议统一验收表'):
    def cell(value):
        # All values are plain text, including filenames and parser reasons.
        return str(value).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('|', '&#124;').replace('\r', ' ').replace('\n', '<br>')
    lines = ['# ' + title, '', '总体状态：' + LABELS[acceptance['overall_status']], '',
             acceptance.get('note', '测量边界以每行说明为准。'), '',
             '| 要求 | 测量口径 | 阈值 | 实测值 | 结果 | 原因 |',
             '|---|---|---|---|---|---|']
    for item in acceptance['rows']:
        lines.append('| ' + ' | '.join(cell(item[key]) for key in
                     ('requirement', 'measurement', 'threshold', 'actual')) + ' | ' +
                     LABELS[item['status']] + ' | ' + cell(item['reason']) + ' |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description='离线重建联合验收表；输入须为同一次run_diagnostics运行。')
    parser.add_argument('directory', type=Path)
    parser.add_argument('--out', type=Path, required=True, help='新输出目录；不覆盖历史报告')
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=False)
    def load(name):
        path = args.directory / name
        if not path.exists(): return {}
        if path.stat().st_size > 64 * 1024 * 1024:
            raise ValueError('Input report exceeds 64MiB bounded reader: ' + name)
        value = json.loads(path.read_text(encoding='utf-8'))
        if not isinstance(value, dict): raise ValueError('Report must be a JSON object: ' + name)
        return value
    result = combined_acceptance(load('sender-report.json'), load('receiver-report.json'), load('summary.json'))
    (args.out/'acceptance.json').write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding='utf-8')
    (args.out/'acceptance.md').write_text(markdown(result), encoding='utf-8')


if __name__ == '__main__':
    main()
